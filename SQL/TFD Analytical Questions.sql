-- Find members who renewed their subscription within 7 days after the previous subscription expired. --
WITH Previous_Subscription AS(
SELECT 
    M.Member_ID,
    M.Member_Name,
    S.Subscription_ID,
    S.Start_Date,
    S.End_Date,
    LAG(S.End_Date) OVER (PARTITION BY M.Member_ID ORDER BY End_Date) AS Previous_End_Date
FROM
    Members M
        JOIN
    Subscriptions S ON M.Member_ID = S.Member_ID
    )

SELECT 
    Member_ID,
    Member_Name,
    Start_Date,
    End_Date,
    Previous_End_Date,
    DATEDIFF(Start_Date, Previous_End_Date) AS Days_to_Renew
FROM
    Previous_Subscription
WHERE
    Previous_End_Date IS NOT NULL
        AND DATEDIFF(Start_Date, Previous_End_Date) BETWEEN 0 AND 7
ORDER BY Member_ID , Start_Date;

-- Display each member's lifetime value (LTV), total attendance count, total subscriptions, and average amount spent in a single query. --
SELECT 
    M.Member_ID,
    M.Member_Name,
    COALESCE(A.LifeTime_Value, 0) AS Lifetime_Value,
    COALESCE(B.Total_Attendance, 0) AS Total_Attendance,
    COALESCE(A.Total_Subscriptions, 0) AS Total_Subscriptions,
    COALESCE(A.Avg_Amount_Spent, 0) AS Average_Amount_Spent
FROM
    Members M
        LEFT JOIN
    (SELECT 
        S.Member_ID,
            COUNT(S.Subscription_ID) AS Total_Subscriptions,
            SUM(P.Amount) AS LifeTime_Value,
            AVG(P.Amount) AS Avg_Amount_Spent
    FROM
        Subscriptions S
    JOIN Payments P ON S.Subscription_ID = P.Subscription_ID
    GROUP BY S.Member_ID) A ON M.Member_ID = A.Member_ID
        LEFT JOIN
    (SELECT 
        Member_ID, COUNT(*) AS Total_Attendance
    FROM
        Attendance
    GROUP BY Member_ID) B ON M.Member_ID = B.Member_ID
ORDER BY M.Member_ID;

-- Using a CTE, calculate the cumulative revenue generated by each branch over time. --
WITH Month_Revenue AS (
SELECT 
    S.Branch_ID,
    DATE_FORMAT(P.Payment_Date, '%Y-%m') AS Revenue_Month,
    SUM(P.Amount) AS Monthly_Revenue
FROM
    Subscriptions S
        JOIN
    Payments P ON S.Subscription_ID = P.Subscription_ID
GROUP BY S.Branch_ID , DATE_FORMAT(P.Payment_Date, '%Y-%m')
)

SELECT 
	B.Branch_Name, 
    M.Revenue_Month, 
    M.Monthly_Revenue,
	SUM(M.Monthly_Revenue) 
		OVER(PARTITION BY M.Branch_ID ORDER BY M.Revenue_Month) AS Cumulative_Revenue
FROM 
	Month_Revenue M 
JOIN Branches B 
	ON M.Branch_ID = B.Branch_ID
ORDER BY B.Branch_ID, M.Revenue_Month;

-- For every branch, identify the member contributing the highest lifetime revenue. --
WITH LTV AS (
SELECT 
    B.Branch_ID, S.Member_ID, SUM(P.Amount) AS Lifetime_Value
FROM
    Payments P
        JOIN
    Subscriptions S ON P.Subscription_ID = S.Subscription_ID
        JOIN
    Branches B ON B.Branch_ID = S.Branch_ID
GROUP BY B.Branch_ID , S.Member_ID
),
Ranking AS (
SELECT 
	Branch_ID, Member_ID, Lifetime_Value,
	ROW_NUMBER() OVER (PARTITION BY Branch_ID ORDER BY Lifetime_Value DESC) AS Ranked
FROM 
	LTV
)
SELECT 
    R.Branch_ID,
    B.Branch_Name,
    R.Member_ID,
    M.Member_Name,
    R.Lifetime_Value
FROM
    Ranking R
        JOIN
    Branches B ON R.Branch_ID = B.Branch_ID
        JOIN
    Members M ON R.Member_ID = M.Member_ID
WHERE
    R.Ranked = 1;
    
-- Build a single SQL query that generates a Branch Performance Report containing the following columns:
-- Branch Name | Total Members | Total Trainers | Total Subscriptions | Total Revenue | Average Member Age | Most Popular Plan | Highest Spending Member | Revenue Rank among all Branches --
WITH
-- TOTAL MEMBERS PER BRANCH -- 
Member_Count AS (
SELECT 
    Branch_ID,
    COUNT(*) AS Total_Members,
    AVG(Age) AS Average_Member_Age
FROM
    Members
GROUP BY Branch_ID
),
-- TOTAL TRAINERS PER BRANCH --
Trainer_Count AS (
SELECT 
    Branch_ID, COUNT(*) AS Total_Trainers
FROM
    Trainers
GROUP BY Branch_ID
),
-- TOTAL SUBSCRIPTIONS AND TOTAL REVENUE --
Subscription_Summary AS (
SELECT 
    Branch_ID,
    COUNT(*) AS Total_Subscriptions,
    SUM(Amount_Paid) AS Total_Revenue
FROM
    Subscriptions
GROUP BY Branch_ID
),
-- MOST POPULAR PLAN --
Popular_Plan AS (
SELECT 
	S.Branch_ID, P.Plan_Name,
	ROW_NUMBER() 
		OVER (PARTITION BY S.Branch_ID ORDER BY COUNT(*) DESC) AS RN
FROM 
	Subscriptions S 
JOIN Plans P 
	ON S.Plan_ID = P.Plan_ID 
GROUP BY S.Branch_ID, P.Plan_Name
),
-- HIGHEST SPENDING CUSTOMER --
Highest_Spender AS (
SELECT 
	Branch_ID, Member_Name, Total_Spent,
    ROW_NUMBER() OVER (PARTITION BY Branch_ID ORDER BY Total_Spent DESC) AS RN
FROM
	(SELECT 
    M.Branch_ID,
    M.Member_Name,
    SUM(S.Amount_Paid) AS Total_Spent
FROM
    Members M
        JOIN
    Subscriptions S ON M.Member_ID = S.Member_ID
GROUP BY M.Branch_ID , M.Member_ID , M.Member_Name) X
)

SELECT 
    B.Branch_Name,
    MC.Total_Members,
    TC.Total_Trainers,
    SS.Total_Subscriptions,
    SS.Total_Revenue,
    ROUND(MC.Average_Member_Age, 2) AS Average_Member_Age,
    PP.Plan_Name AS Most_Popular_Plan,
    HS.Member_Name AS Highest_Spending_Member,
	DENSE_RANK() OVER(ORDER BY SS.Total_Revenue DESC) AS Revenue_Rank
FROM
    Branches B
        LEFT JOIN
    Member_Count MC ON B.Branch_ID = MC.Branch_ID
        LEFT JOIN
    Trainer_Count TC ON B.Branch_ID = TC.Branch_ID
        LEFT JOIN
    Subscription_Summary SS ON B.Branch_ID = SS.Branch_ID
        LEFT JOIN
    Popular_Plan PP ON B.Branch_ID = PP.Branch_ID
        LEFT JOIN
    Highest_Spender HS ON B.Branch_ID = HS.Branch_ID AND HS.RN = 1
ORDER BY Revenue_Rank;