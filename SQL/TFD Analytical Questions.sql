-- Find the trainer-to-member ratio for every branch. --
SELECT 
    B.Branch_ID,
    B.Branch_Name,
    COALESCE(M.Member_Count, 0) AS Total_Members,
    COALESCE(T.Trainer_Count, 0) AS Total_Trainers,
    ROUND(COALESCE(M.Member_Count, 0) / NULLIF(T.Trainer_Count, 0),
            2) AS Member_to_Ratio
FROM
    Branches B
        LEFT JOIN
    (SELECT 
        Branch_ID, COUNT(*) AS Member_Count
    FROM
        Members
    GROUP BY Branch_ID) M ON B.Branch_ID = M.Branch_ID
        LEFT JOIN
    (SELECT 
        Branch_ID, COUNT(*) AS Trainer_Count
    FROM
        Trainers
    GROUP BY Branch_ID) T ON B.Branch_ID = T.Branch_ID
ORDER BY B.Branch_ID;

-- EXPERT LEVEL --
-- Rank members within each branch based on their total spending using a window function. --
WITH Members_Spending AS (
SELECT 
    M.Member_ID,
    M.Member_Name,
    B.Branch_ID,
    B.Branch_Name,
    B.City,
    SUM(P.Amount) AS Total_Spend
FROM
    Members M
        JOIN
    Branches B ON M.Branch_ID = B.Branch_ID
        JOIN
    Payments P ON M.Member_ID = P.Member_ID
GROUP BY M.Member_ID , M.Member_Name , B.Branch_ID , B.Branch_Name , B.City
)

SELECT 
    Branch_ID, Branch_Name, Member_Name, Total_Spend,
	ROW_NUMBER() OVER(PARTITION BY Branch_ID ORDER BY Total_Spend DESC) AS Ranked
FROM
    Members_Spending;
    
-- For every member, display the current subscription along with the previous subscription. --
SELECT
    S.Member_ID,
    S.Subscription_ID,
    P.Plan_Name AS Current_Plan,
    S.Start_Date,
    S.End_Date,

    LAG(S.Subscription_ID)
        OVER (
            PARTITION BY S.Member_ID
            ORDER BY S.Start_Date
        ) AS Previous_Subscription_ID,

    LAG(P.Plan_Name)
        OVER (
            PARTITION BY S.Member_ID
            ORDER BY S.Start_Date
        ) AS Previous_Plan,

    LAG(S.Start_Date)
        OVER (
            PARTITION BY S.Member_ID
            ORDER BY S.Start_Date
        ) AS Previous_Start_Date,

    LAG(S.End_Date)
        OVER (
            PARTITION BY S.Member_ID
            ORDER BY S.Start_Date
        ) AS Previous_End_Date

FROM Subscriptions S
JOIN Plans P
ON S.Plan_ID = P.Plan_ID
ORDER BY
    S.Member_ID,
    S.Start_Date;
    
-- Calculate the revenue growth percentage for every month compared to the previous month. --
WITH Current_Revenue AS(
SELECT 
    DATE_FORMAT(Payment_Date, '%Y-%m') AS Months,
    SUM(Amount) AS Monthly_Revenue
FROM
    Payments
GROUP BY Months
ORDER BY Months),

Revenue_Comparison AS(
SELECT 
	Months, 
    Monthly_Revenue, 
    LAG(Monthly_Revenue) 
		OVER (ORDER BY Months) AS Previous_Month_Revenue
FROM 
	Current_Revenue
)

SELECT 
    Months,
    Monthly_Revenue,
    Previous_Month_Revenue,
    ROUND((Monthly_Revenue - Previous_Month_Revenue) * 100.0 / Previous_Month_Revenue,
            2) AS Revenue_Growth_Perc
FROM
    Revenue_Comparison; 
    
